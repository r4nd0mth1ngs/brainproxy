fn timeout(strength: Strength) -> Duration {
    Duration::from_millis(match strength {
        Strength::Low => 1000,
        Strength::Medium => 3000,
        Strength::High => 6000,
        Strength::Insane => 12000,
    })
}

fn client_hello(version: [u8; 2]) -> Vec<u8> {
    let message_len = 2 + HELLO.len();
    let record_len = message_len + 4;
    let mut out = vec![HANDSHAKE, version[0], version[1], (record_len >> 8) as u8, record_len as u8];
    out.extend([CLIENT_HELLO, (message_len >> 16) as u8, (message_len >> 8) as u8, message_len as u8]);
    out.extend(version);
    out.extend(HELLO);
    out
}

/// One TLS record (type, payload), or `None` on EOF, error, or timeout.
async fn read_record(s: &mut Stream, wait: Duration) -> Option<(u8, Vec<u8>)> {
    tokio::time::timeout(wait, async {
        let mut head = [0u8; 5];
        s.read_exact(&mut head).await.ok()?;
        let mut payload = vec![0u8; u16::from_be_bytes([head[3], head[4]]) as usize];
        s.read_exact(&mut payload).await.ok()?;
        Some((head[0], payload))
    })
    .await
    .ok()
    .flatten()
}

/// Whether the server answers the empty heartbeat with more than the 3 bytes sent.
async fn probe(s: &mut Stream, version: [u8; 2], wait: Duration) -> bool {
    if s.write_all(&client_hello(version)).await.is_err() || s.flush().await.is_err() {
        return false;
    }
    // Read until a handshake record that starts with ServerHelloDone (ZAP's test).
    let mut records = 0;
    loop {
        let Some((typ, payload)) = read_record(s, wait).await else { return false };
        if typ == HANDSHAKE && payload.first() == Some(&SERVER_HELLO_DONE) {
            break;
        }
        records += 1;
        if records > 64 {
            return false;
        }
    }
    let mut heartbeat = vec![HEARTBEAT, version[0], version[1]];
    heartbeat.extend(HEARTBEAT_BODY);
    if s.write_all(&heartbeat).await.is_err() || s.flush().await.is_err() {
        return false;
    }
    let deadline = Instant::now() + wait;
    while Instant::now() <= deadline {
        let Some((typ, payload)) = read_record(s, deadline.saturating_duration_since(Instant::now())).await else {
            return false;
        };
        match typ {
            HEARTBEAT => return payload.len() > 3,
            // A fatal alert; warnings are ignored.
            ALERT_RECORD if payload.first() == Some(&2) => return false,
            _ => {}
        }
    }
    false
}

pub struct HeartBleed;

impl ActiveRule for HeartBleed {
    fn id(&self) -> u32 {
        20015
    }

    fn name(&self) -> &'static str {
        "Heartbleed OpenSSL Vulnerability"
    }

    fn alerts(&self) -> &'static [&'static AlertDef] {
        &ALERTS
    }

    fn scope(&self) -> RuleScope {
        RuleScope::Host
    }

    fn scan<'a>(&'a self, cx: &'a Cx) -> BoxFuture<'a> {
        Box::pin(async move {
            let host = cx.target().host.clone();
            let port = if cx.target().port == 80 { 443 } else { cx.target().port };
            let wait = timeout(cx.strength());
            for (name, version) in VERSIONS {
                let Ok(Ok(mut s)) = tokio::time::timeout(wait, cx.connect_raw(&host, port)).await else {
                    return; // can't connect at all (or out of scope): no point in continuing
                };
                if probe(&mut s, version, wait).await {
                    let info = format!(
                        "This issue was confirmed by exfiltrating data from the server, using {name}. This is \
                         unlikely to be a false positive."
                    );
                    cx.report(ALERT.raise("", "").other_info(info), cx.base_response());
                }
            }
        })
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn client_hello_framing() {
        let h = client_hello([3, 3]);
        assert_eq!(HELLO.len(), 748);
        assert_eq!(&h[..5], &[0x16, 3, 3, 0x02, 0xf2]); // record length 754
        assert_eq!(&h[5..11], &[0x01, 0x00, 0x02, 0xee, 3, 3]); // message length 750
        assert_eq!(h.len(), 5 + 754);
        // The heartbeat extension (type 0x000f, length 1, peer_allowed_to_send) ends it.
        assert_eq!(&h[h.len() - 5..], &[0x00, 0x0f, 0x00, 0x01, 0x01]);
    }
}
