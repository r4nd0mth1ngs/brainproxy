//! Ported from ZAP HeartBleedActiveScanRule (ascanrules, Apache License 2.0).
//!
//! Sends ZAP's ClientHello (heartbeat extension included) for TLS 1.0, 1.1 and 1.2, waits for
//! ServerHelloDone, then sends a heartbeat request that claims a 16 KiB payload but carries
//! none. A heartbeat response longer than 3 bytes means the server echoed process memory.
//! The returned bytes are only measured, never stored or reported.
//!
//! The connection is a raw TCP stream from the guarded client (`Cx::connect_raw`), so the
//! engagement scope applies as for every other request. Like ZAP, port 80 is tested on 443.

